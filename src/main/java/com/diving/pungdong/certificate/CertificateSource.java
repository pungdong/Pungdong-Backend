package com.diving.pungdong.certificate;

/**
 * 자격증 발급 출처. <b>사용자가 고르는 값이 아니라 강의 연결 여부에서 파생</b>된다 —
 * 등록 요청에 이 필드가 없고 서버가 정한다.
 *
 * <p>왜: "풍덩 발급"의 실체는 "풍덩 강의에서 땄다"이다. 클라이언트가 직접 고를 수 있으면
 * <b>강사 없는 풍덩 발급</b>이라는 모순 상태를 만들 수 있다(FE 결정 로그 2026-08-14 와 동일 규칙 —
 * FE 는 UX 로 막고 여기서 구조적으로 막는다).
 */
public enum CertificateSource {
    /** 풍덩 강의 수료로 취득 — 발급 강사·강의가 함께 박제된다. */
    PUNGDONG,
    /** 외부 취득 — 강의 연결 없음. */
    EXTERNAL
}
