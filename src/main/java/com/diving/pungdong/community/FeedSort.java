package com.diving.pungdong.community;

/**
 * 피드 정렬 — <b>화이트리스트 enum</b>이다. 클라이언트가 준 문자열을 {@code Pageable} 에 그대로 태우면
 * 임의 필드 정렬로 내부 컬럼을 탐색하거나 인덱스 없는 정렬로 풀스캔을 유발할 수 있다.
 *
 * <p>디자인의 "일정 임박순"({@code MATCH} 기본 정렬)은 여기 없다 — 그 정렬 pill 이 있는 화면이 Phase 1
 * 범위 밖이라 <b>트리거할 UI 가 없다.</b> 값만 남기면 죽은 옵션이 되므로,
 * {@code ?category=MATCH} 의 서버 기본값으로만 살렸다. 정렬 pill 이 생기면 그때 여기 올린다.
 */
public enum FeedSort {

    /** 최신순 — 기본값. */
    LATEST,

    /**
     * 인기순 — <b>최근 7일 안에서</b> 좋아요 많은 순.
     *
     * <p>기간을 자르지 않으면 한 번 인기를 얻은 오래된 글이 영구히 상단을 차지해 피드가 굳는다.
     * 댓글 가중치는 넣지 않았다 — 데이터가 쌓인 뒤 튜닝할 문제고, 지금 임의 가중치를 넣으면
     * 근거 없는 숫자가 랭킹을 좌우한다.
     */
    POPULAR
}
