package com.diving.pungdong.community;

/**
 * 신고 사유. 디자인에 사유 시트가 없어 BE 가 정의한 목록이고, 확정되면 FE 시트에 그대로 노출된다.
 *
 * <p>{@link #COMMERCIAL} 이 있는 게 중요하다 — 같이가요의 "영리 활동(강습·투어 판매) 금지" 가드에서
 * 기계적으로 강제할 수 있는 건 "MATCH 글에 강의를 연결할 수 없다" 뿐이고, 본문에 광고를 쓰는 건
 * 자동 판정하지 않는다(오탐이 크다). 그 나머지의 실제 집행 경로가 이 사유다.
 */
public enum ReportReason {

    /** 도배·스팸. */
    SPAM,

    /** 욕설·비방·괴롭힘. */
    ABUSE,

    /** 선정적 콘텐츠. */
    SEXUAL,

    /** 영리 활동·광고 — 같이가요 가드의 집행 경로. */
    COMMERCIAL,

    /** 허위 정보. 다이빙은 안전과 직결돼 잘못된 정보의 무게가 크다. */
    FALSE_INFO,

    /** 기타 — 이 값이면 상세 설명을 필수로 받는다. */
    OTHER
}
